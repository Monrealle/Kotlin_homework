package battleship.domain.repository

import battleship.domain.model.EloRating
import battleship.domain.model.Game
import battleship.domain.model.Player

/**
 * =============================================================================================
 * Контракты репозиториев Domain-слоя.
 *
 * Интерфейсы описывают операции, необходимые бизнес-логике игры,
 * но не знают, где именно хранятся данные.
 *
 * Реализации репозиториев находятся в Infrastructure-слое.
 *
 * Такое разделение позволяет менять способ хранения данных
 * (in-memory, JSON, SQLite и т.д.) без изменения Domain-логики.
 * =============================================================================================
 */

/**
 * =============================================================================================
 * Репозиторий игровых партий.
 *
 * Определяет операции сохранения и поиска объектов [Game].
 * =============================================================================================
 */
interface GameRepository {

    /**
     * Сохраняет игровую партию.
     *
     * @param game партия для сохранения
     */
    fun save(game: Game)

    /**
     * Возвращает все сохранённые партии.
     *
     * @return список всех партий
     */
    fun findAll(): List<Game>

    /**
     * Ищет партию по уникальному идентификатору.
     *
     * @param id идентификатор партии
     * @return найденная партия или `null`
     */
    fun findById(id: String): Game?

    /**
     * Возвращает все партии указанного игрока.
     *
     * @param player игрок
     * @return список партий, в которых участвовал игрок
     */
    fun findByPlayer(player: Player): List<Game>
}

/**
 * =============================================================================================
 * Репозиторий игроков.
 *
 * Определяет операции сохранения и поиска объектов [Player].
 * =============================================================================================
 */
interface PlayerRepository {

    /**
     * Сохраняет игрока.
     *
     * @param player игрок для сохранения
     */
    fun save(player: Player)

    /**
     * Возвращает всех сохранённых игроков.
     *
     * @return список игроков
     */
    fun findAll(): List<Player>

    /**
     * Ищет игрока по идентификатору.
     *
     * @param id идентификатор игрока
     * @return найденный игрок или `null`
     */
    fun findById(id: String): Player?

    /**
     * Ищет игрока по имени без учёта регистра.
     *
     * @param name имя игрока
     * @return найденный игрок или `null`
     */
    fun findByName(name: String): Player?
}

/**
 * =============================================================================================
 * Репозиторий рейтингов Эло.
 *
 * Хранит актуальный рейтинг каждого игрока.
 * =============================================================================================
 */
interface EloRatingRepository {

    /**
     * Сохраняет текущий рейтинг игрока.
     *
     * @param rating объект рейтинга для сохранения
     */
    fun save(rating: EloRating)

    /**
     * Возвращает текущий рейтинг указанного игрока.
     *
     * @param player игрок
     * @return объект [EloRating] с текущим рейтингом
     */
    fun findByPlayer(player: Player): EloRating
}
