package battleship.domain.model

/**
 * =============================================================================================
 * Игрок.
 *
 * Представляет реального участника партии «Морского боя».
 * Хранит уникальный идентификатор и отображаемое имя.
 *
 * @param id уникальный идентификатор игрока
 * @param name отображаемое имя игрока
 * =============================================================================================
 */
data class Player(
    val id: String,
    val name: String
) {
    init {
        require(name.trim().isNotEmpty()) { "Имя игрока не может быть пустым" }
    }

    override fun toString(): String = name
}
