package battleship.infrastructure

import battleship.domain.model.EloRating
import battleship.domain.model.Player
import battleship.domain.repository.EloRatingRepository
import battleship.domain.repository.PlayerRepository
import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import java.io.File

/**
 * =============================================================================================
 * Инфраструктурный слой: файловые репозитории для сохранения игроков и рейтингов.
 *
 * Архитектурное решение:
 *
 * Вместо чистого in-memory хранения используются JSON-файлы
 * в домашней директории пользователя.
 *
 * Это позволяет сохранять данные между запусками приложения.
 *
 * Внутри репозиториев используется оперативный кэш:
 *
 * 1. При создании репозитория данные загружаются из файла.
 * 2. Дальнейшая работа выполняется с объектами в памяти.
 * 3. После каждой операции сохранения изменённое состояние записывается на диск.
 *
 * Структура:
 *
 * - [FilePlayerRepository] - сохранение игроков.
 * - [FileEloRatingRepository] - сохранение текущих рейтингов Эло.
 *
 * Репозитории реализуют интерфейсы Domain-слоя:
 *
 * - [PlayerRepository]
 * - [EloRatingRepository]
 * =============================================================================================
 */

/**
 * =============================================================================================
 * Репозиторий игроков с сохранением в JSON-файл.
 *
 * Данные хранятся в файле:
 *
 * `~/.battleship/players.json`
 *
 * При создании репозитория файл загружается в оперативный кэш.
 * После каждого сохранения кэш полностью записывается обратно в файл.
 *
 * @param dataDir директория для хранения файлов.
 *                По умолчанию используется `~/.battleship`.
 * =============================================================================================
 */
class FilePlayerRepository(
    dataDir: File = defaultDataDir()
) : PlayerRepository {

    /**
     * Файл, в котором хранятся игроки.
     */
    private val file =
        File(dataDir, "players.json")

    /**
     * Оперативный кэш игроков.
     *
     * Ключ - уникальный идентификатор игрока.
     * Значение - объект [Player].
     */
    private val cache =
        mutableMapOf<String, Player>()

    /**
     * Настройки JSON-сериализации.
     *
     * prettyPrint позволяет хранить файл в читаемом виде.
     */
    private val json =
        Json {
            prettyPrint = true
        }

    init {

        /**
         * Создаём директорию хранилища,
         * если она ещё отсутствует.
         */
        dataDir.mkdirs()

        /**
         * Загружаем существующих игроков из файла.
         */
        load()
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Сохраняет игрока в кэш и немедленно записывает изменения на диск.
     *
     * @param player игрок для сохранения
     * ---------------------------------------------------------------------------------------------
     */
    override fun save(player: Player) {

        cache[player.id] = player

        persist()
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Возвращает список всех сохранённых игроков.
     *
     * @return список игроков
     * ---------------------------------------------------------------------------------------------
     */
    override fun findAll(): List<Player> =
        cache.values.toList()

    /**
     * ---------------------------------------------------------------------------------------------
     * Ищет игрока по уникальному идентификатору.
     *
     * @param id идентификатор игрока
     * @return найденный игрок или `null`
     * ---------------------------------------------------------------------------------------------
     */
    override fun findById(id: String): Player? =
        cache[id]

    /**
     * ---------------------------------------------------------------------------------------------
     * Ищет игрока по имени без учёта регистра.
     *
     * Например, `Alex`, `alex` и `ALEX`
     * считаются одним и тем же именем.
     *
     * @param name имя игрока
     * @return найденный игрок или `null`
     * ---------------------------------------------------------------------------------------------
     */
    override fun findByName(name: String): Player? =
        cache.values.find {
            it.name.equals(
                name,
                ignoreCase = true
            )
        }

    /* ── Внутренняя работа с файлом ────────────────────────────────────────── */

    /**
     * ---------------------------------------------------------------------------------------------
     * Загружает игроков из JSON-файла в оперативный кэш.
     *
     * Если файл отсутствует, загрузка не выполняется:
     * предполагается, что приложение запускается впервые.
     *
     * При повреждённом JSON программа получает исключение,
     * чтобы ошибка не скрывалась от разработчика.
     * ---------------------------------------------------------------------------------------------
     */
    private fun load() {

        if (!file.exists()) {
            return
        }

        val data =
            json.decodeFromString<List<PlayerDto>>(
                file.readText()
            )

        data.forEach {
            cache[it.id] =
                Player(
                    id = it.id,
                    name = it.name
                )
        }
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Сохраняет текущее состояние кэша в JSON-файл.
     *
     * Для сериализации используются внутренние DTO,
     * чтобы инфраструктурный слой не зависел от деталей хранения
     * Domain-объектов.
     * ---------------------------------------------------------------------------------------------
     */
    private fun persist() {

        val data =
            cache.values.map {
                PlayerDto(
                    id = it.id,
                    name = it.name
                )
            }

        file.writeText(
            json.encodeToString(data)
        )
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Внутренний DTO для сериализации игрока.
     *
     * @param id идентификатор игрока
     * @param name имя игрока
     * ---------------------------------------------------------------------------------------------
     */
    @Serializable
    private data class PlayerDto(
        val id: String,
        val name: String
    )

    companion object {

        /**
         * ---------------------------------------------------------------------------------------------
         * Возвращает директорию по умолчанию для хранения данных.
         *
         * Используется:
         *
         * `~/.battleship`
         *
         * @return директория хранения данных
         * ---------------------------------------------------------------------------------------------
         */
        fun defaultDataDir(): File =
            File(
                System.getProperty("user.home"),
                ".battleship"
            )
    }
}

/**
 * =============================================================================================
 * Репозиторий рейтингов Эло с сохранением в JSON-файл.
 *
 * Данные хранятся в файле:
 *
 * `~/.battleship/ratings.json`
 *
 * Внутри используется кэш:
 *
 * playerId -> rating
 *
 * После изменения рейтинга данные немедленно записываются на диск.
 *
 * @param dataDir директория для хранения файлов
 * =============================================================================================
 */
class FileEloRatingRepository(
    dataDir: File = FilePlayerRepository.defaultDataDir()
) : EloRatingRepository {

    /**
     * Файл с сохранёнными рейтингами.
     */
    private val file =
        File(dataDir, "ratings.json")

    /**
     * Оперативный кэш рейтингов.
     *
     * Ключ - идентификатор игрока.
     * Значение - текущий рейтинг.
     */
    private val cache =
        mutableMapOf<String, Int>()

    /**
     * Настройки JSON-сериализации.
     */
    private val json =
        Json {
            prettyPrint = true
        }

    init {

        /**
         * Создаём директорию,
         * если она ещё отсутствует.
         */
        dataDir.mkdirs()

        /**
         * Загружаем сохранённые рейтинги.
         */
        load()
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Сохраняет новый рейтинг игрока и записывает изменения на диск.
     *
     * @param rating объект рейтинга для сохранения
     * ---------------------------------------------------------------------------------------------
     */
    override fun save(rating: EloRating) {

        cache[rating.player.id] =
            rating.rating

        persist()
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Возвращает текущий рейтинг указанного игрока.
     *
     * Если игрок ещё не имеет сохранённого рейтинга,
     * используется начальное значение [EloRating.INITIAL_RATING].
     *
     * @param player игрок
     * @return объект [EloRating] с актуальным рейтингом
     * ---------------------------------------------------------------------------------------------
     */
    override fun findByPlayer(
        player: Player
    ): EloRating =
        EloRating(
            player = player,
            rating = cache[player.id]
                ?: EloRating.INITIAL_RATING
        )

    /**
     * ---------------------------------------------------------------------------------------------
     * Загружает рейтинги из JSON-файла в оперативный кэш.
     *
     * Если файл отсутствует, загрузка не выполняется.
     * ---------------------------------------------------------------------------------------------
     */
    private fun load() {

        if (!file.exists()) {
            return
        }

        val data =
            json.decodeFromString<List<RatingDto>>(
                file.readText()
            )

        data.forEach {
            cache[it.playerId] =
                it.rating
        }
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Сохраняет текущее состояние рейтингов в JSON-файл.
     * ---------------------------------------------------------------------------------------------
     */
    private fun persist() {

        val data =
            cache.map { (playerId, rating) ->

                RatingDto(
                    playerId = playerId,
                    rating = rating
                )
            }

        file.writeText(
            json.encodeToString(data)
        )
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Внутренний DTO для сериализации рейтинга.
     *
     * Хранит только необходимые для восстановления данные:
     *
     * - идентификатор игрока;
     * - значение рейтинга.
     *
     * @param playerId идентификатор игрока
     * @param rating значение рейтинга
     * ---------------------------------------------------------------------------------------------
     */
    @Serializable
    private data class RatingDto(
        val playerId: String,
        val rating: Int
    )
}
