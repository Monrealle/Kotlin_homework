package battleship.application

import battleship.domain.model.Coordinate
import battleship.domain.model.Game
import battleship.domain.model.Move
import battleship.domain.model.Player
import battleship.domain.model.Ship
import battleship.domain.model.ValidationResult

/**
 * =============================================================================================
 * Координатор игровой сессии (Application-слой).
 *
 * Определяет контракт управления жизненным циклом одной партии:
 * создание, расстановку кораблей, выполнение ходов и получение состояния.
 *
 * Сессия работает только с двумя реальными игроками.
 * Способ расстановки кораблей выбирается внешним слоем: GUI предлагает ручной ввод
 * и дополнительную автоматическую генерацию.
 *
 * @see GameSessionImpl
 * =============================================================================================
 */
interface GameSession {

    /**
     * ---------------------------------------------------------------------------------------------
     * Начать новую партию между двумя игроками.
     *
     * @param p1 первый игрок
     * @param p2 второй игрок
     * ---------------------------------------------------------------------------------------------
     */
    fun startGame(p1: Player, p2: Player)

    /**
     * ---------------------------------------------------------------------------------------------
     * Расставить корабли для указанного игрока.
     *
     * Валидация расстановки выполняется реализацией через [ShipPlacementValidator].
     *
     * @param player игрок, для которого задаётся расстановка
     * @param ships список кораблей
     * @return результат валидации
     * ---------------------------------------------------------------------------------------------
     */
    fun placeShips(player: Player, ships: List<Ship>): ValidationResult

    /**
     * ---------------------------------------------------------------------------------------------
     * Выполнить ход игрока.
     *
     * Ход проходит через [TurnValidator], после чего передаётся на доску соперника.
     *
     * @param player игрок, делающий ход
     * @param coord координата выстрела
     * @return объект [Move], описывающий совершённый ход
     * ---------------------------------------------------------------------------------------------
     */
    fun makeMove(player: Player, coord: Coordinate): Move

    /**
     * ---------------------------------------------------------------------------------------------
     * Получить текущее состояние партии.
     *
     * @return объект [Game] с текущим состоянием партии
     * ---------------------------------------------------------------------------------------------
     */
    fun getGame(): Game
}
