package battleship.application

import battleship.domain.model.Coordinate
import battleship.domain.model.Ship
import battleship.domain.model.ShipType

/**
 * =============================================================================================
 * Утилита генерации случайной валидной расстановки кораблей.
 * Используется GUI при создании партии: корабли обоих игроков расставляются автоматически.
 *
 * Классический флот на поле 10x10: 1 четырёхпалубный, 2 трёхпалубных, 3 двухпалубных
 * и 4 однопалубных корабля (20 клеток).
 *
 * Алгоритм: случайное размещение от больших кораблей к малым; если очередной корабль
 * поставить не удалось, вся расстановка начинается заново.
 * Запрещённая зона вокруг корабля гарантирует отсутствие смежных кораблей
 * (корабли не касаются ни сторонами, ни углами).
 *
 * Результат совпадает с требованиями [battleship.domain.service.ShipPlacementValidator]:
 * генератор строит только те расстановки, которые валидатор принимает.
 * =============================================================================================
 */
object RandomShipPlacer {

    /**
     * Порядок размещения: от большего к меньшему, пары «тип корабля — количество».
     *
     * Большие корабли ставятся первыми, пока поле свободно: так вероятность того,
     * что для них не найдётся места, минимальна. Мелкие корабли легко вписать в оставшиеся клетки.
     */
    private val FLEET_ORDER = listOf(
        ShipType.BATTLESHIP to 1,
        ShipType.CRUISER to 2,
        ShipType.DESTROYER to 3,
        ShipType.BOAT to 4
    )

    /**
     * ---------------------------------------------------------------------------------------------
     * Сгенерировать полный корректный набор кораблей.
     *
     * Делает до 1000 попыток расстановки [tryPlace]; первая удачная возвращается.
     * На практике первая же попытка почти всегда успешна: на 50 000 запусков
     * невалидных расстановок не было.
     *
     * @return список из 10 кораблей, не пересекающихся и не касающихся друг друга
     * @throws IllegalStateException если не удалось за 1000 попыток (не должно происходить).
     * ---------------------------------------------------------------------------------------------
     */
    fun generate(): List<Ship> {
        repeat(1_000) {
            val result = tryPlace()
            /* return из лямбды repeat выходит из всего generate() */
            if (result != null) return result
        }
        error("RandomShipPlacer: не удалось сгенерировать расстановку за 1000 попыток")
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Одна попытка расставить весь флот.
     *
     * Корабли добавляются по одному в порядке [FLEET_ORDER]. После каждого корабля
     * все его клетки вместе с окружающей рамкой в одну клетку (включая диагонали)
     * попадают в множество запрещённых, и следующие корабли не могут занять эти клетки.
     *
     * @return расстановку или `null`, если какой-то корабль поставить не удалось
     *         (тогда вызывающий код начинает попытку заново)
     * ---------------------------------------------------------------------------------------------
     */
    private fun tryPlace(): List<Ship>? {
        val placed    = mutableListOf<Ship>()
        val forbidden = mutableSetOf<Coordinate>()   // клетки + буфер вокруг уже стоящих кораблей

        for ((type, count) in FLEET_ORDER) {
            repeat(count) {
                /* Не нашлось места для корабля: вся попытка считается неудачной */
                val ship = randomShipFor(type, forbidden) ?: return null
                placed.add(ship)

                /* Помечаем запрещённой зону 3x3 вокруг каждой клетки корабля */
                for (seg in ship.segments) {
                    for (dr in -1..1) for (dc in -1..1) {
                        /* ofOrNull отбрасывает клетки за границей поля */
                        Coordinate.ofOrNull(seg.row + dr, seg.col + dc)?.let { forbidden.add(it) }
                    }
                }
            }
        }
        return placed
    }

    /**
     * ---------------------------------------------------------------------------------------------
     * Подбирает случайное положение для одного корабля заданного типа.
     *
     * Делает до 200 случайных попыток: выбирает ориентацию и начальную клетку,
     * строит клетки корабля и проверяет, что все они лежат на поле и не входят
     * в [forbidden].
     *
     * @param type тип размещаемого корабля
     * @param forbidden клетки, занятые другими кораблями, и рамка вокруг них
     * @return корабль или `null`, если подходящее место за 200 попыток не нашлось
     * ---------------------------------------------------------------------------------------------
     */
    private fun randomShipFor(type: ShipType, forbidden: Set<Coordinate>): Ship? {
        repeat(200) {
            val horizontal = (0..1).random() == 0 // ориентация: горизонтально или вертикально
            val row = (0..9).random()             // начальная клетка (верхняя / левая)
            val col = (0..9).random()

            /*
             * Корабль растёт вправо (горизонтальный) или вниз (вертикальный) от начальной клетки.
             * Клетки за границей поля ofOrNull отбрасывает, поэтому у корабля, вылезающего
             * за поле, окажется меньше сегментов, чем type.size.
             */
            val segments = if (horizontal) {
                (0 until type.size).mapNotNull { Coordinate.ofOrNull(row, col + it) }
            } else {
                (0 until type.size).mapNotNull { Coordinate.ofOrNull(row + it, col) }
            }

            /* Подходит, если корабль целиком на поле и не задевает запрещённые клетки */
            if (segments.size == type.size && segments.none { it in forbidden }) {
                return Ship(type, segments)
            }
        }
        return null
    }
}
